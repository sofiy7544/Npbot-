// ─────────────────────────────────────────────────────────────────────
// Final dedup + assembly + index
// ─────────────────────────────────────────────────────────────────────

// Dedup with set, then keep multi-word first
const _seen = new Set<string>();
const _all: string[] = [];
for (const c of [...MULTI_WORD_CITIES, ...SINGLE_WORD_CITIES]) {
  const k = c.toLowerCase();
  if (!_seen.has(k)) { _seen.add(k); _all.push(c); }
}

export const ALL_UA_CITIES: readonly string[] = Object.freeze(_all);

/** Index by first letter (lowercase) — O(1) bucket lookup, O(bucket_size) scan. */
const CITY_INDEX: Map<string, readonly string[]> = (() => {
  const m = new Map<string, string[]>();
  for (const city of _all) {
    const k = city[0]!.toLowerCase();
    let bucket = m.get(k);
    if (!bucket) { bucket = []; m.set(k, bucket); }
    bucket.push(city);
  }
  // freeze each bucket
  const out = new Map<string, readonly string[]>();
  for (const [k, v] of m.entries()) out.set(k, Object.freeze(v));
  return out;
})();

/** Get all cities whose name starts with `letter` (case-insensitive). */
export function citiesByFirstLetter(letter: string): readonly string[] {
  return CITY_INDEX.get(letter.toLowerCase()) ?? [];
}

